RULESETS_IMPORT_PY = '''#!/usr/bin/env python3
"""Compose imports.tf pairing each default phase-entrypoint ruleset exported
from the SOURCE zone with its counterpart on the TARGET zone (matched by phase).

Usage: rulesets-import.py SRC_ZONE DST_ZONE SRC_TOKEN DST_TOKEN > imports.tf
Reads the resource declarations from ./zone.tf in the current directory."""
import json, os, re, sys, urllib.request

def api(path, token):
    req = urllib.request.Request("https://api.cloudflare.com/client/v4" + path,
                                 headers={"Authorization": "Bearer " + token})
    body = json.load(urllib.request.urlopen(req))
    if not body.get("success"):
        sys.exit(f"[ERR] {path}: {body.get('errors')}")
    return body["result"]

src_zone, dst_zone, src_token, dst_token = sys.argv[1:5]
src = {r["id"]: r["phase"] for r in api(f"/zones/{src_zone}/rulesets", src_token)
       if r.get("kind") == "zone"}
dst = {r["phase"]: r["id"] for r in api(f"/zones/{dst_zone}/rulesets", dst_token)
       if r.get("kind") == "zone"}

# the exported resource names embed the SOURCE ruleset id (terraform_managed_resource_<id>_<n>)
name_by_src_id = {}
if os.path.exists("zone.tf"):
    for name in re.findall(r'resource "cloudflare_ruleset" "(terraform_managed_resource_[^"]+)"',
                           open("zone.tf").read()):
        m = re.search(r"([0-9a-f]{32})", name)
        if m:
            name_by_src_id[m.group(1)] = name

out = ["# ---------------------------------------------------------------------------",
       "# Default phase-entrypoint rulesets exist on every zone -- IMPORT, never create.",
       "# id = <TARGET_ZONE_ID>/<TARGET_RULESET_ID>, matched by phase to the source.",
       "# Auto-generated by rulesets-import.py.",
       "# ---------------------------------------------------------------------------",
       ""]
n = 0
for src_id, phase in sorted(src.items(), key=lambda kv: kv[1]):
    if phase not in dst:
        print(f"# NOTE: phase {phase} has no entrypoint on the target zone", file=sys.stderr)
        continue
    name = name_by_src_id.get(src_id)
    if not name:
        continue
    out += ["import {", f"  to = cloudflare_ruleset.{name}   # {phase}",
            f'  id = "{dst_zone}/{dst[phase]}"', "}", ""]
    n += 1
print("\\n".join(out))
print(f"# {n} import blocks generated", file=sys.stderr)
'''

SETUP_SH = """\
#!/usr/bin/env bash
# One-shot workspace setup for the '@@SVC@@' service:
#   1. locate a terraform binary    2. export (runs once; --fresh to redo)
#   3. remap SOURCE -> TARGET ids   4. (security only) compose imports.tf
#   5. terraform init
#
#  tokens:   CF_SOURCE_TOKEN = source-account token  (exports + import mapping)
#           CLOUDFLARE_API_TOKEN = target-account token (terraform apply)
set -euo pipefail
cd "$(dirname "$0")"

SRC_ACCOUNT_ID="@@SRC_ACCOUNT_ID@@"
SRC_ZONE_ID="@@SRC_ZONE_ID@@"
DST_ACCOUNT_ID="@@DST_ACCOUNT_ID@@"
DST_ZONE_ID="@@DST_ZONE_ID@@"

# -- 1. terraform binary (cf-terraforming requires it in the CWD) ------------
if [ ! -x ./terraform ]; then
    if command -v terraform >/dev/null 2>&1; then
        cp "$(command -v terraform)" ./terraform
        chmod +x ./terraform || true
    else
        echo "ERROR: no terraform binary in CWD or on PATH" >&2
        exit 1
    fi
fi

# -- 2. export (skip when already done; rerun with: setup.sh --fresh) --------
EXP_TOKEN="${CF_SOURCE_TOKEN:-${CLOUDFLARE_API_TOKEN:-}}"
if [ "${1:-}" = "--fresh" ] || [ ! -f .exported ]; then
    if [ -z "$EXP_TOKEN" ]; then
        echo "ERROR: set CF_SOURCE_TOKEN (source account) for the export step" >&2
        exit 1
    fi
    CLOUDFLARE_API_TOKEN="$EXP_TOKEN" bash export.sh
    date > .exported
fi

# -- 3. remap SOURCE -> TARGET ids in the exported files ----------------------
if [ -n "$DST_ACCOUNT_ID" ] && [ -n "$DST_ZONE_ID" ]; then
    for f in $(ls *.tf 2>/dev/null); do
        case "$f" in
            provider.tf|variables.tf|terraform.tfvars|versions.tf|imports.tf) continue ;;
        esac
        sed -i.bak \
            -e "s/$SRC_ZONE_ID/$DST_ZONE_ID/g" \
            -e "s/$SRC_ACCOUNT_ID/$DST_ACCOUNT_ID/g" \
            "$f"
    done
    rm -f *.bak
else
    cat >&2 <<WARN
WARNING: target account/zone IDs are not configured -- the exported files still
         reference the SOURCE account. Regenerate with:
             --services . --target-account-id <acct> --target-zone-id <zone>
WARN
fi

# -- 4. (security/) compose imports.tf for the default ruleset entrypoints ----
if [ -f rulesets-import.py ]; then
    if [ -n "$DST_ZONE_ID" ] && [ -n "${CF_SOURCE_TOKEN:-}" ] && [ -n "${CLOUDFLARE_API_TOKEN:-}" ]; then
        python3 rulesets-import.py "$SRC_ZONE_ID" "$DST_ZONE_ID" \\
            "$CF_SOURCE_TOKEN" "$CLOUDFLARE_API_TOKEN" > imports.tf
        echo "imports.tf: $(grep -c '^import ' imports.tf) rulesets to import into the target"
    else
        cat >&2 <<WARN
NOTE: skipping imports.tf -- set CF_SOURCE_TOKEN=<source token> and
      CLOUDFLARE_API_TOKEN=<target token> to auto-generate it
WARN
    fi
fi

# -- 5. init ------------------------------------------------------------------
[ -d .terraform ] || terraform init -input=false -upgrade

echo "== '@@SVC@@' ready. Review terraform.tfvars, then: terraform plan && terraform apply"
"""

EXPORT_ALL_HEADER = """\
#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"

# ordered: dependencies first; networking LAST (spectrum needs an ACTIVE zone -
# run its setup/apply only after the NS cutover).
# Pass --fresh to re-run cf-terraforming for every workspace.

"""


def render_setup(svc, src_aid, src_zid, dst_aid, dst_zid):
    return (SETUP_SH
            .replace("@@SVC@@", svc)
            .replace("@@SRC_ACCOUNT_ID@@", src_aid)
            .replace("@@SRC_ZONE_ID@@", src_zid)
            .replace("@@DST_ACCOUNT_ID@@", dst_aid or "")
            .replace("@@DST_ZONE_ID@@", dst_zid or ""))
